"""Import factual regular-season pairings from the pinned CC0 Openfootball checkout.
python scripts/import-special-schedules.py /path/to/football.json
No scores, executable source, player assets or historical champions are imported.
"""
from pathlib import Path
import json,sys,subprocess,unicodedata,re
root=Path(__file__).resolve().parents[1];source=Path(sys.argv[1]).resolve()
commit=subprocess.check_output(['git','-C',str(source),'rev-parse','HEAD'],text=True).strip()
if commit!='e6744429ee395bc86f247348c6184bb08d4eb361':raise ValueError('Unexpected source revision')
pack=json.loads((root/'web/data/world-leagues.json').read_text())
def norm(s):
 s=''.join(c for c in unicodedata.normalize('NFKD',s.lower()) if not unicodedata.combining(c))
 return ' '.join(w for w in re.sub('[^a-z0-9 ]',' ',s).split() if w not in {'fc','cf','sc','club','de','ca','cd'})
index={norm(p['club']['name']):p['club']['id'] for p in pack['clubs']}
configs={'mls':'2025/mls.json','argentina':'2025/ar.1.json','colombia':'2025/co.1.json'}
cohorts={
 'mls':['Atlanta United FC','Charlotte FC','Chicago Fire','Columbus Crew','D.C. United','FC Cincinnati','Inter Miami CF','Nashville SC','New England Revolution','New York City FC','New York RB','Orlando City','Philadelphia Union','CF Montréal','Toronto FC'],
 'argentina':['Aldosivi','Argentinos Juniors','Banfield','Barracas Central','Belgrano de Córdoba','Boca Juniors','Central Córdoba SdE','Defensa y Justicia','Estudiantes','Huracán','Independiente Rivadavia',"Newell's Old Boys",'Racing Club','Tigre','Unión de Santa Fe']
}
result={}
for key,path in configs.items():
 data=json.loads((source/path).read_text());matches=data['matches']
 fixtures=[]
 for m in matches:
  a,b=index.get(norm(m['team1'])),index.get(norm(m['team2']))
  if not a or not b:raise ValueError((m['team1'],m['team2']))
  r=int(re.search(r'(\d+)$',m['round']).group(1))
  fixtures.append([a,b,r])
 ids=sorted({id for fixture in fixtures for id in fixture[:2]})
 groups=[]
 if key in cohorts:
  first=[index[norm(name)] for name in cohorts[key]];groups=[first,[id for id in ids if id not in first]]
  if [len(g) for g in groups]!=[15,15]:raise ValueError('Invalid cohorts')
  for id in ids:
   own=next(g for g in groups if id in g)
   intra=sum(1 for a,b,_ in fixtures if id in [a,b] and a in own and b in own)
   cross=sum(1 for a,b,_ in fixtures if id in [a,b] and not(a in own and b in own))
   expected=(28,6) if key=='mls' else (14,2)
   if (intra,cross)!=expected:raise ValueError((key,id,intra,cross))
 result[key]={'groups':groups,'source':f'https://github.com/openfootball/football.json/blob/{commit}/{path}','fixtures':fixtures}
(root/'src/data/special-schedules.ts').write_text('// Generated by scripts/import-special-schedules.py. CC0 pairings; dates/results are simulated.\nexport const SPECIAL_SCHEDULES: Readonly<Record<string,{source:string;groups:readonly (readonly string[])[];fixtures:readonly (readonly [string,string,number])[]}>> = '+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n')
print({k:len(v['fixtures']) for k,v in result.items()})
